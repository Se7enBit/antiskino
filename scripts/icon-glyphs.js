// Writes src/ui/iconGlyphs.ts: the Material Community icons the app uses, with
// their font codes, so bundles don't carry all ~7,000 icon names (180 KB).
// Add icons: node scripts/icon-glyphs.js <name> [<name>…] (keeps the existing
// ones; names must exist in Material Community Icons, see pictogrammers.com).
// Remove one by deleting its line and running the script with no names.
const fs = require('fs');
const path = require('path');

const all = require('@expo/vector-icons/build/vendor/react-native-vector-icons/glyphmaps/MaterialCommunityIcons.json');
const target = path.join(process.cwd(), 'src', 'ui', 'iconGlyphs.ts');

const current = fs.existsSync(target)
  ? [...fs.readFileSync(target, 'utf8').matchAll(/^ {2}'?([a-z0-9-]+)'?:/gm)].map((m) => m[1])
  : [];
const names = [...new Set([...current, ...process.argv.slice(2)])].sort();
const unknown = names.filter((n) => all[n] === undefined);
if (unknown.length) {
  process.stderr.write(`Not Material Community icons: ${unknown.join(', ')}\n`);
  process.exit(1);
}
// Quotes only where needed, as Prettier writes them.
const key = (n) => (/^[a-z][a-z0-9]*$/.test(n) ? n : `'${n}'`);
const lines = names.map((n) => `  ${key(n)}: ${all[n]},`).join('\n');
fs.writeFileSync(
  target,
  `// Generated by scripts/icon-glyphs.js: the icons the app uses and their font codes.\n` +
    `// Add one with: node scripts/icon-glyphs.js <name>\n` +
    `export const ICON_GLYPHS = {\n${lines}\n} as const;\n`,
);
